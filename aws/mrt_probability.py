def get_mrt_value(ts: datetime) -> int:
    """
    Return the MRT coefficient for the given timestamp.

    • If ts.hour ≥ 15 (3 pm), the night counts toward the *next* calendar day.
    • If the date is missing (beyond 2026-01-31), default to **0**.
    """
    date_key = (ts + timedelta(days=1) if ts.hour >= 15 else ts).date().isoformat()
    return MRT_VALUES.get(date_key, 0)
